"""
Referral packet export endpoint for IP-SAKTI Sahayak (Task Su-01/Su-03).
Generates user-controlled informational packets for referral without automated transmission.
"""

import uuid
from datetime import datetime, timezone
from fastapi import APIRouter
from ...models.schemas import Intake, ReferralPacket, JurisdictionEnum

router = APIRouter(prefix="/api/v1/referral", tags=["Referral"])


@router.post(
    "/export",
    response_model=ReferralPacket,
    summary="Export Referral Packet",
    description=(
        "Generates a structured, user-downloadable referral packet containing formulation facts, "
        "assumptions, and cited provisions. User initiates any contact; no automated dispatch."
    ),
)
def export_referral_packet(intake: Intake) -> ReferralPacket:
    packet_id = f"REF-{uuid.uuid4().hex[:8].upper()}"
    timestamp = datetime.now(timezone.utc).isoformat()

    unresolved_issues = []
    if intake.has_novel_ingredient:
        unresolved_issues.append("Novel / non-classical ingredients require CDSCO / Ayush regulatory validation.")
    if intake.claims_disease_cure:
        unresolved_issues.append("Curative claims require formal clinical trial evidence or First Schedule classical basis.")
    if not intake.classical_text_reference and intake.intended_use == "medicinal":
        unresolved_issues.append("Lack of classical authoritative text citation requires proprietary medicine licensing review.")

    summary = (
        f"Referral intake dossier for: {intake.formulation_title}. "
        f"Intended use: {intake.intended_use}. "
        f"Ingredients listed: {', '.join(intake.ingredients)}."
    )

    return ReferralPacket(
        packet_id=packet_id,
        query_summary=summary,
        provisional_route=None,
        jurisdiction=intake.jurisdiction or JurisdictionEnum.INDIA,
        assumptions=[
            "Formulation details submitted by user in self-directed intake session.",
            "Independent verification of herbal species authenticity required."
        ],
        cited_provisions=[
            "Drugs and Cosmetics Act 1940, Section 3(a) & 3(h)",
            "The Patents Act 1970, Section 3(p)"
        ],
        unresolved_issues=unresolved_issues,
        export_timestamp=timestamp,
        disclaimer=(
            "This informational packet was generated by IP-SAKTI Sahayak for user consultation "
            "with a qualified Ayurveda regulatory expert or patent attorney. It does not constitute legal counsel."
        ),
    )
